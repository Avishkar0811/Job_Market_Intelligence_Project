-- Run this script in your Oracle connection. Keep the older JOBS1 table intact.
CREATE TABLE JOBS_REAL
 (
    JOB_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_TITLE VARCHAR2(200),
    JOB_CATEGORY VARCHAR2(150),
    COMPANY_NAME VARCHAR2(200),
    LOCATION_CITY VARCHAR2(100),
    LOCATION_STATE VARCHAR2(100),
    LOCATION_COUNTRY VARCHAR2(100),
    WORK_MODE VARCHAR2(50),
    SALARY_MINIMUM NUMBER(15,2),
    SALARY_MAXIMUM NUMBER(15,2),
    SALARY_CURRENCY VARCHAR2(10),
    EXPERIENCE_LEVEL VARCHAR2(100),
    EXPERIENCE_REQUIRED VARCHAR2(100),
    SKILLS_EXTRACTED VARCHAR2(2000),
    POSTED_DATE DATE
);

-- Verify table exists and is initially empty.
SELECT COUNT(*) AS ROW_COUNT FROM JOBS_REAL;
